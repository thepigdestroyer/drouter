import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { ARTIFACT_PATH, ROOT } from "./arc-common.mjs";

const require = createRequire(import.meta.url);
const solc = require("solc");

const source = readFileSync(join(ROOT, "contracts/DRouterRegistry.sol"), "utf8");
const input = {
  language: "Solidity",
  sources: { "DRouterRegistry.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
for (const e of output.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);

const contract = output.contracts["DRouterRegistry.sol"].DRouterRegistry;
const abi = contract.abi;
const bytecode = `0x${contract.evm.bytecode.object}`;

mkdirSync(dirname(ARTIFACT_PATH), { recursive: true });
writeFileSync(ARTIFACT_PATH, `${JSON.stringify({ abi, bytecode }, null, 2)}\n`);
writeFileSync(
  join(dirname(ARTIFACT_PATH), "abi.ts"),
  `// Generated by scripts/arc-compile.mjs. Do not edit.\nexport const registryAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);

console.log(`Compiled DRouterRegistry: ${abi.length} ABI entries, ${(bytecode.length - 2) / 2} bytes of bytecode`);
